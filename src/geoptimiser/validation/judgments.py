"""Hand-written judgments for every catalog feature (docs/validation).

These are *assessments*, not facts. Each one records what the feature claims, how strong
the support for that claim is, where it can be wrong, and what should happen next. The
derived columns of the matrix (status, source location, thresholds, tests) come from the
code and are never written here. Confidence says how sure the *assessment* is, which is
not the same as how accurate the check is: no check has been benchmarked on real pages.
"""

from dataclasses import dataclass

# benefit classes
TECH = "technical correctness"
CRAWL = "crawlability or indexability"
EXTRACT = "content extraction or machine readability"
ENTITY = "structured-data or entity interpretation"
AIR = "AI-answer retrieval or citation"
BIZ = "business outcome"
OTHER = "other: search-result presentation"
OTHER_A11Y = "other: accessibility"
OTHER_PERF = "other: delivery performance"

# claim strength
STANDARD = "specified by a standard or vendor documentation"
PLAUSIBLE = "plausible mechanism, not measured"
HYPOTHESIS = "hypothesis about ranking, AI retrieval or citation; unvalidated"
NONE = "none: not implemented"

# threshold basis
SPEC = "specification"
DOC = "vendor documentation (secondary summary)"
HEUR = "configurable heuristic"
ARB = "arbitrary default"
NA = "n/a (no numeric threshold)"
# dispositions
RETAIN, REVISE, INFO, REMOVE, INVESTIGATE = (
    "Retain",
    "Revise",
    "Informational only",
    "Remove",
    "Investigate",
)


@dataclass(frozen=True)
class Judgment:
    benefit: str
    claim: str
    strength: str
    sources: tuple[str, ...]
    threshold_basis: str
    false_positives: str
    false_negatives: str
    discriminates: str
    actionable: str
    disposition: str
    confidence: str
    followup: str
    overlap: str = ""


def J(*args: object, **kw: object) -> Judgment:
    return Judgment(*args, **kw)  # type: ignore[arg-type]



"""Per-feature implementation level, validation level and disposition, as shipped data.

``feature_levels.json`` is generated by ``python -m geoptimiser.validation.matrix
--write`` from the same rows as ``docs/validation/feature_validation_matrix.csv`` and
checked by ``--check``, so the API (``/api/v1/catalog``) and the frontend show exactly
what the matrix says without needing the test tree at runtime.
"""

import json
from functools import cache
from pathlib import Path
from typing import Any

LEVELS_PATH = Path(__file__).with_name("feature_levels.json")


@cache
def validation_levels() -> dict[str, dict[str, Any]]:
    """feature_id -> {implementation_level, validation_level, disposition, ...}.

    Empty when the generated file is missing (never invented at runtime).
    """
    try:
        data = json.loads(LEVELS_PATH.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    return {row["feature_id"]: row for row in data.get("features", [])}



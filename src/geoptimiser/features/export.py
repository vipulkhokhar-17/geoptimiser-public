"""Generated, checked-in views of the catalog: JSON for machines, Markdown for people."""

import json
from collections import Counter

from geoptimiser.features.catalog import FeatureCatalog, FeatureDefinition
from geoptimiser.features.catalog_data import CATALOG
from geoptimiser.features.config import FeatureConfig
from geoptimiser.features.scoring import _CREDIT, SCORING_VERSION


def catalog_json(catalog: FeatureCatalog = CATALOG) -> str:
    return catalog.to_json()


def scoring_json() -> str:
    policy = {
        "version": SCORING_VERSION,
        "unit_credit": _CREDIT,
        "excluded_from_denominator": ["not_applicable", "not_measured", "error"],
        "group_score": "unweighted mean of measured scored features' pass rates",
        "min_reportable_coverage": FeatureConfig().min_reportable_coverage,
        "reportability": "a group's score may be displayed only when feature coverage "
        "reaches min_reportable_coverage (inclusive); consumers show reported_score",
        "not_contributing": "features that cannot discriminate under the crawl "
        "configuration, and results that only repeat another result, are kept out of "
        "the aggregate (features/contribution.py)",
        "see": "docs/DECISIONS.md ADR-0012 and geoptimiser/features/scoring.py",
    }
    return json.dumps(policy, indent=2) + "\n"


def _entry(f: FeatureDefinition) -> str:
    lines = [
        f"#### {f.feature_id} — {f.name}",
        "",
        f"{f.description} *Why:* {f.rationale}",
        "",
        f"- **Status:** {f.implementation_status}"
        f"{' (heuristic)' if f.is_heuristic else ''}; scope `{f.scope}`; pillar `{f.pillar}`;"
        f" {'scored' if f.scored else 'unscored'}; check version {f.check_version}",
        f"- **Measures:** {f.measurement} Output: {f.output_type}"
        f"{f' ({f.unit})' if f.unit else ''}.",
        f"- **Inputs:** {', '.join(f.inputs)}",
        f"- **Applicability:** {f.applicability}",
        f"- **Method:** {f.method}",
        f"- **Evidence:** {f.evidence_requirements}",
        f"- **Severity:** {f.severity_policy}",
        f"- **Scoring:** {f.scoring_policy}",
        f"- **Limitations:** {' '.join(f.limitations)}",
    ]
    if f.blocked_by:
        lines.append(f"- **Blocked by:** {' '.join(f.blocked_by)}")
    if f.config_keys:
        lines.append(
            f"- **Configuration:** {', '.join(f'`{k}`' for k in f.config_keys)}"
        )
    if f.overlaps:
        lines.append(
            "- **Related features:** "
            + " ".join(f"{o.feature_id}: {o.distinction}" for o in f.overlaps)
        )
    if f.remediation:
        lines.append(f"- **Remediation:** {f.remediation}")
    lines.append(f"- **Tests:** {f.test_requirements}")
    return "\n".join(lines)


def catalog_markdown(catalog: FeatureCatalog = CATALOG) -> str:
    status = Counter(f.implementation_status for f in catalog.features)
    out = [
        "# GEO feature catalog",
        "",
        "<!-- Generated by `python -m geoptimiser.features --export`. Do not edit by hand. -->",
        "",
        f"Catalog version {catalog.version}: **{len(catalog.features)} features** in "
        f"{len(catalog.categories)} categories. Source of truth: "
        "`src/geoptimiser/features/catalog_data.py`; machine-readable copy: "
        "`configs/feature_catalog.json`. IDs are stable and never renumbered.",
        "",
        "| Status | Meaning | Features |",
        "|---|---|---|",
        f"| implemented | A working check runs against Stage 01/02 output | {status['implemented']} |",
        f"| partial | A check runs but covers only part of the feature (see its limitations) | {status['partial']} |",
        f"| planned | Defined; blocked by a named data source or stage; reported `not_measured` | {status['planned']} |",
        f"| unavailable | Needs a capability that is not on the roadmap; reported `not_measured` | {status['unavailable']} |",
        "",
        "A *planned* or *unavailable* feature is never reported as measured. Results use the "
        "states `pass`, `fail`, `not_applicable`, `not_measured` and `error`. `warning` is emitted only by the intent-dependent features (owner-controlled settings), which are unscored.",
        "",
        "## Overview",
        "",
    ]
    for category in catalog.categories:
        out += [
            f"### {category.code}. {category.name}",
            "",
            category.description,
            "",
            "| ID | Name | Status | Scope | Scored | Heuristic |",
            "|---|---|---|---|---|---|",
        ]
        for f in catalog.by_category(category.code):
            out.append(
                f"| {f.feature_id} | {f.name} | {f.implementation_status} | {f.scope} | "
                f"{'yes' if f.scored else 'no'} | {'yes' if f.is_heuristic else 'no'} |"
            )
        out.append("")
    out += ["## Definitions", ""]
    for category in catalog.categories:
        out += [f"### {category.code}. {category.name}", ""]
        for f in catalog.by_category(category.code):
            out += [_entry(f), ""]
    return "\n".join(out).rstrip("\n") + "\n"
